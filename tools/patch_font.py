def encode_matrix_to_2bpp(matrix_16x16):
    """Encodes a 16x16 string matrix (#'s and spaces) into 64 bytes of 2bpp data."""
    gbytes = bytearray()
    for row_str in matrix_16x16:
        for b_idx in range(4):
            chunk = row_str[b_idx * 4 : (b_idx + 1) * 4]
            byte_val = 0
            for shift_idx, ch in enumerate(chunk):
                # 3 = solid bright white (matches original font)
                val = 3 if ch != ' ' else 0
                byte_val |= (val << (6 - shift_idx * 2))
            gbytes.append(byte_val)
    return bytes(gbytes)

def main():
    if not os.path.exists(RAW_FONT_PATH):
        print(f"Error: {RAW_FONT_PATH} missing.")
        return

    with open(RAW_FONT_PATH, "rb") as f:
        font_data = bytearray(f.read())

    for i in range(26):
        ch = chr(ord('a') + i)
        matrix = PIXEL_FONT[ch]
        gbytes = encode_matrix_to_2bpp(matrix)
        gid = LOWERCASE_START_GID + i
        start = gid * BYTES_PER_GLYPH
        font_data[start : start + BYTES_PER_GLYPH] = gbytes

    with open(PATCHED_FONT_PATH, "wb") as f:
        f.write(font_data)

    print(f"Injected 26 bespoke pixel-art lowercase glyphs into slots {LOWERCASE_START_GID}-{LOWERCASE_START_GID+25}.")

if __name__ == "__main__":
    main()
